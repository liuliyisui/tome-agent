"""Small replaceable runtime boundaries; no database or API framework dependency."""
from typing import Protocol
from .domain import Snapshot

class CheckpointStore(Protocol):
    def initialize(self,state:Snapshot)->None: ...
    def load(self,identifier:str)->Snapshot: ...
    def commit(self,state:Snapshot,expected_revision:int)->None: ...
    def save_audit(self,identifier:str,attempt_id:str,record:dict)->None: ...

class Agent(Protocol):
    role: str
    def run(self,context:dict,trace:list)->dict: ...

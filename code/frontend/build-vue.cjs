/* Compile only our checked-in template. No runtime compiler or eval is shipped. */
const fs = require("node:fs");
const path = require("node:path");
let compiler;
try {
  compiler = require("@vue/compiler-dom");
} catch {
  compiler = require("../backend/data/vue-build/node_modules/@vue/compiler-dom");
}
const html = fs.readFileSync(path.join(__dirname, "index.html"), "utf8");
const template = html.match(
  /<template id="tome-template">([\s\S]*)<\/template>/,
);
if (!template) throw new Error("Missing Vue source template");
const { code } = compiler.compile(template[1], {
  mode: "function",
  prefixIdentifiers: true,
  hoistStatic: true,
});
const output =
  "/* Generated by build-vue.cjs from index.html. Vue 3.5.44; do not edit. */\n" +
  "window.TomeRender = (function () {\n" +
  code +
  "\n})();\n";
const destination = path.join(__dirname, "vue-components.js");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(destination, "utf8") !== output) {
    throw new Error(
      "Vue template changed: run npm --prefix code/frontend run build",
    );
  }
} else {
  fs.writeFileSync(destination, output);
}
console.log(
  "Compiled Tome Vue template (runtime-only, strict CSP compatible).",
);
